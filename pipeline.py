"""ETL pipeline: clean raw e-commerce data, load it into SQLite,
run the SQL aggregations in queries.sql, and write REPORT.md plus a
monthly-revenue chart.

Re-runnable end to end with one command:
    python pipeline.py
"""
import sqlite3

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

DB_PATH = "outputs/ecommerce.db"
REPORT_PATH = "outputs/REPORT.md"


def extract() -> tuple[pd.DataFrame, pd.DataFrame]:
    orders = pd.read_csv("data/raw_orders.csv")
    events = pd.read_csv("data/raw_events.csv")
    return orders, events


def clean_orders(raw: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    stats = {"raw_rows": len(raw)}
    df = raw.copy()
    df = df.drop_duplicates()
    stats["after_dedup"] = len(df)
    df["order_date"] = pd.to_datetime(df["order_date"], errors="coerce")
    df = df.dropna(subset=["order_date", "region", "product_id"])
    stats["after_missing_and_bad_dates"] = len(df)
    df = df[df["quantity"] > 0]
    stats["after_bad_quantity"] = len(df)
    df["revenue"] = (df["quantity"] * df["unit_price"]).round(2)
    stats["clean_rows"] = len(df)
    return df, stats


def clean_events(raw: pd.DataFrame) -> pd.DataFrame:
    df = raw.copy()
    df = df.drop_duplicates()
    df["event_date"] = pd.to_datetime(df["event_date"], errors="coerce")
    df = df.dropna(subset=["event_date"])
    return df


def load(orders: pd.DataFrame, events: pd.DataFrame) -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.execute("DROP TABLE IF EXISTS orders")
    conn.execute("DROP TABLE IF EXISTS events")
    conn.execute("""
        CREATE TABLE orders (
            order_id INTEGER PRIMARY KEY,
            customer_id INTEGER NOT NULL,
            order_date TEXT NOT NULL,
            product_id TEXT NOT NULL,
            product_name TEXT NOT NULL,
            category TEXT NOT NULL,
            quantity INTEGER NOT NULL,
            unit_price REAL NOT NULL,
            region TEXT NOT NULL,
            revenue REAL NOT NULL
        )
    """)
    conn.execute("""
        CREATE TABLE events (
            event_id INTEGER PRIMARY KEY,
            customer_id INTEGER NOT NULL,
            event_type TEXT NOT NULL,
            event_date TEXT NOT NULL,
            product_id TEXT NOT NULL
        )
    """)
    orders.to_sql("orders", conn, if_exists="append", index=False)
    events.to_sql("events", conn, if_exists="append", index=False)
    conn.execute("CREATE INDEX idx_orders_date ON orders(order_date)")
    conn.execute("CREATE INDEX idx_orders_category ON orders(category)")
    conn.execute("CREATE INDEX idx_orders_customer ON orders(customer_id)")
    conn.execute("CREATE INDEX idx_events_type ON events(event_type)")
    conn.commit()
    return conn


def run_queries(conn: sqlite3.Connection) -> dict[str, pd.DataFrame]:
    with open("queries.sql") as f:
        sql = f.read()
    statements = [s.strip() for s in sql.split(";") if s.strip()]
    names = ["revenue_by_category", "monthly_revenue", "top_products",
             "repeat_customer_rate"]
    return {name: pd.read_sql_query(stmt, conn)
            for name, stmt in zip(names, statements)}


def df_to_md(df: pd.DataFrame) -> str:
    """Render a DataFrame as a Markdown table (no extra dependencies)."""
    cols = list(df.columns)
    header = "| " + " | ".join(cols) + " |"
    sep = "| " + " | ".join(["---"] * len(cols)) + " |"
    rows = ["| " + " | ".join(str(v) for v in row) + " |"
            for row in df.itertuples(index=False)]
    return "\n".join([header, sep] + rows)


def write_report(stats: dict, results: dict[str, pd.DataFrame]) -> None:
    total_revenue = results["revenue_by_category"]["revenue"].sum()
    total_orders = len(pd.read_sql_query("SELECT 1 FROM orders",
                                         sqlite3.connect(DB_PATH)))
    lines = [
        "# E-Commerce ETL Report",
        "",
        "Generated by `pipeline.py` from the synthetic raw files in `data/`.",
        "",
        "## Cleaning summary",
        "",
        f"- Raw order rows: {stats['raw_rows']}",
        f"- After dropping duplicates: {stats['after_dedup']}",
        f"- After dropping missing values and bad dates: "
        f"{stats['after_missing_and_bad_dates']}",
        f"- After dropping non-positive quantities: {stats['after_bad_quantity']}",
        f"- Clean orders loaded: {stats['clean_rows']}",
        "",
        "## Headline numbers",
        "",
        f"- Total orders: {total_orders}",
        f"- Total revenue: ${total_revenue:,.2f}",
        f"- Average order value: ${total_revenue / total_orders:,.2f}",
        "",
        "## Revenue by category",
        "",
        df_to_md(results["revenue_by_category"]),
        "",
        "## Monthly revenue",
        "",
        df_to_md(results["monthly_revenue"]),
        "",
        "## Top 10 products by revenue",
        "",
        df_to_md(results["top_products"]),
        "",
        "## Repeat-customer rate",
        "",
        df_to_md(results["repeat_customer_rate"]),
        "",
    ]
    with open(REPORT_PATH, "w") as f:
        f.write("\n".join(lines))
    print(f"Wrote {REPORT_PATH}")


def write_chart(monthly: pd.DataFrame) -> None:
    fig, ax = plt.subplots(figsize=(10, 5))
    ax.bar(monthly["month"], monthly["revenue"])
    ax.set_xlabel("Month")
    ax.set_ylabel("Revenue ($)")
    ax.set_title("Monthly Revenue — 2024")
    ax.tick_params(axis="x", rotation=30)
    fig.tight_layout()
    fig.savefig("outputs/monthly_revenue.png", dpi=150)
    print("Saved outputs/monthly_revenue.png")


def main() -> None:
    raw_orders, raw_events = extract()
    orders, stats = clean_orders(raw_orders)
    events = clean_events(raw_events)
    print(f"Cleaning: {stats['raw_rows']} raw rows -> "
          f"{stats['clean_rows']} clean rows")
    conn = load(orders, events)
    results = run_queries(conn)
    write_report(stats, results)
    write_chart(results["monthly_revenue"])
    print(f"Total revenue: "
          f"${results['revenue_by_category']['revenue'].sum():,.2f}")
    conn.close()


if __name__ == "__main__":
    main()
